#!/usr/bin/env bash
# One-shot environment setup on an SCG login node.
# Assumes you can ssh into login.scg.stanford.edu and have a SUNet account.
#
# Optional env vars:
#   SCG_VENV_DIR  - where to create the venv (default: <repo>/student_pkg/.venv).
#                   Set this to /labs/<lab>/<your_dir>/venv if your $HOME
#                   quota is too small for ~6 GB of torch + triton.
#   SCG_CUDA_MOD  - name of the CUDA module to load (default: cuda).
#                   On SCG try `module avail cuda` to find the exact name.

set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &> /dev/null && pwd)
REPO_ROOT=$(cd "$SCRIPT_DIR/../.." &> /dev/null && pwd)
VENV_DIR="${SCG_VENV_DIR:-$REPO_ROOT/student_pkg/.venv}"
CUDA_MOD="${SCG_CUDA_MOD:-cuda}"

echo "Repo root: $REPO_ROOT"
echo "Venv:      $VENV_DIR"
echo "CUDA mod:  $CUDA_MOD"

# Load CUDA on the login node so torch/triton can find it during install.
if command -v module >/dev/null 2>&1; then
    module load "$CUDA_MOD" 2>/dev/null || {
        echo "Warning: 'module load $CUDA_MOD' failed."
        echo "Run 'module avail cuda' to find the right module name and re-export"
        echo "  SCG_CUDA_MOD=<name> before re-running this script."
    }
    if [ -z "${CUDA_HOME:-}" ] && command -v nvcc >/dev/null 2>&1; then
        export CUDA_HOME="$(dirname "$(dirname "$(which nvcc)")")"
    fi
fi

# Install uv if not present.
if ! command -v uv >/dev/null 2>&1; then
    echo "Installing uv..."
    curl -LsSf https://astral.sh/uv/install.sh | sh
    export PATH="$HOME/.cargo/bin:$HOME/.local/bin:$PATH"
fi

# Build the venv at the user-specified location.
mkdir -p "$(dirname "$VENV_DIR")"
if [ ! -d "$VENV_DIR" ]; then
    uv venv --python 3.11 "$VENV_DIR"
fi

# shellcheck disable=SC1091
source "$VENV_DIR/bin/activate"

# Core deps.
uv pip install --upgrade pip
uv pip install \
    "torch==2.4.0" \
    "triton>=3.0.0" \
    "transformers>=4.43" \
    "datasets>=2.20" \
    "accelerate>=0.33" \
    "huggingface_hub>=0.24" \
    "numpy<2" \
    "pytest" \
    "pybind11" \
    "matplotlib" \
    "lm_eval"

# Build the C++ extension (CPU correctness path).
cd "$REPO_ROOT/student_pkg"
python setup_ext.py build_ext --inplace

# CPU-only sanity checks.
echo
echo "--- CPU correctness ---"
python -m pytest tests/test_correctness.py -v -k "reference" || true

echo
echo "--- SKA recurrence + manual backward (CPU) ---"
cd "$REPO_ROOT/experiments/backend"
python ska_recurrence.py

echo
echo "--- Model sizing ---"
python ska_model.py

# Persist the venv path so subsequent scripts find it.
SHIM_FILE="$REPO_ROOT/.scg_env"
cat > "$SHIM_FILE" <<EOF
# Generated by setup_scg.sh; sourced by the SCG slurm scripts.
export SCG_VENV_DIR="$VENV_DIR"
export SCG_CUDA_MOD="$CUDA_MOD"
EOF

echo
echo "Setup complete. Wrote $SHIM_FILE."
echo
echo "Next steps:"
echo
echo "  1. Set HF_TOKEN for FineWeb-Edu (recommended even though it's public):"
echo "       echo 'export HF_TOKEN=hf_XXXXXXXXXXXX' >> ~/.bashrc"
echo "       source ~/.bashrc"
echo
echo "  2. Discover your SLURM environment (tells you what to put in the slurm scripts):"
echo "       sinfo -o '%.18P %.10l %.30G %.6D'"
echo "       sacctmgr show user \$USER --associations -p"
echo "       module avail cuda 2>&1 | head"
echo
echo "  3. Set the SCG-specific submission variables in your shell or via sbatch --export:"
echo "       export SCG_PARTITION=<your_partition>"
echo "       export SCG_ACCOUNT=<PI_SUNetID>"
echo "       export SCG_GRES='gpu:<type>:<count>'   # e.g. gpu:h200:8 or gpu:a100:8"
echo "       export SCG_TIME=24:00:00"
echo
echo "  4. Submit sanity:"
echo "       sbatch experiments/scg/run_train_sanity.slurm"
